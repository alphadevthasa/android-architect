// Integrity of the vendored tools in .ai/tools: what writeAiDir vendors, and checks of a copy against it.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { hashTree, regularFiles } from './hash.js';
import { readManifest } from './manifest.js';

/** The package.json written next to the vendored scripts so plain `node` runs them as ES modules. */
export const TOOLS_PACKAGE_JSON = '{"type":"module","private":true}\n';
export const TRUST_FLAG = '--trust-modified-tools';
export const MODIFIED_MESSAGE =
  '.ai/tools was modified since it was generated; run "refresh" with the installed android-architect, or rerun with --trust-modified-tools';

const byText = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const sha = (data) => crypto.createHash('sha256').update(data).digest('hex');

/**
 * Read the files writeAiDir vendors into .ai/tools, as [relPath, Buffer] with paths relative to .ai/tools
 * (scripts/**, catalog/**, package.json). Throws on a symlink in a source, or when a source lives inside `aiDir`
 * (a vendored copy cannot be its own reference).
 */
export function collectVendorSources(skillDir, catalogDir, { aiDir } = {}) {
  const realAi = aiDir ? (fs.existsSync(aiDir) ? fs.realpathSync(aiDir) : path.resolve(aiDir)) : null;
  const sources = [
    ['scripts', path.join(skillDir, 'scripts')],
    ['catalog', catalogDir],
  ].flatMap(([destRel, srcDir]) => {
    const realSrc = fs.realpathSync(srcDir);
    if (realAi && (realSrc === realAi || realSrc.startsWith(realAi + path.sep))) {
      throw new Error(
        `refusing to vendor from inside .ai (${srcDir}): a vendored copy cannot regenerate .ai; run the installed skill or npx android-architect`,
      );
    }
    return regularFiles(srcDir).map((rel) => [`${destRel}/${rel}`, fs.readFileSync(path.join(srcDir, rel))]);
  });
  sources.push(['package.json', Buffer.from(TOOLS_PACKAGE_JSON)]);
  return sources.sort(([a], [b]) => byText(a, b));
}

/** sha256 of every file writeAiDir would vendor, keyed like manifest.tools. */
export function expectedToolHashes(skillDir, catalogDir, opts) {
  return Object.fromEntries(collectVendorSources(skillDir, catalogDir, opts).map(([rel, data]) => [rel, sha(data)]));
}

function diffHashes(actual, expected) {
  const keys = (o) => Object.keys(o).sort(byText);
  const changed = keys(actual).filter((k) => k in expected && actual[k] !== expected[k]);
  const added = keys(actual).filter((k) => !(k in expected));
  const removed = keys(expected).filter((k) => !(k in actual));
  return { changed, added, removed };
}

function hashTools(aiDir) {
  const dir = path.join(aiDir, 'tools');
  return fs.existsSync(dir) ? hashTree(dir) : {};
}

const unverifiable = (reason) => ({ status: 'unverifiable', changed: [], added: [], removed: [], reason });

/**
 * Compare <root>/.ai/tools with what the given (installed) skill would vendor. The manifest is never the reference;
 * it only has to name the same tool version.
 */
export function verifyTools(root, { skillDir, catalogDir, toolVersion }) {
  const aiDir = path.join(root, '.ai');
  catalogDir = catalogDir ?? path.join(skillDir, 'catalog');
  let manifest;
  try {
    manifest = readManifest(aiDir);
  } catch (e) {
    return unverifiable(e.message);
  }
  if (!manifest) return unverifiable('no .ai/manifest.json');
  if (manifest.toolVersion !== toolVersion) {
    return unverifiable(
      `.ai was generated by android-architect ${manifest.toolVersion ?? 'unknown'}, this is ${toolVersion}; run "refresh" with version ${toolVersion}, or "update" to install the matching version`,
    );
  }
  let expected;
  try {
    expected = expectedToolHashes(skillDir, catalogDir, { aiDir });
  } catch (e) {
    return unverifiable(e.message);
  }
  let actual;
  try {
    actual = hashTools(aiDir);
  } catch (e) {
    return { status: 'modified', changed: [], added: [], removed: [], reason: e.message };
  }
  const diff = diffHashes(actual, expected);
  const status = diff.changed.length || diff.added.length || diff.removed.length ? 'modified' : 'ok';
  return { status, ...diff };
}

/**
 * The weaker check for a vendored copy run without the skill: <aiDir>/tools against <aiDir>/manifest.json tools.
 * Someone who rewrites both passes it.
 */
export function selfCheckTools(aiDir) {
  let manifest;
  let actual;
  try {
    manifest = readManifest(aiDir);
    actual = hashTools(aiDir);
  } catch (e) {
    return { status: 'modified', changed: [], added: [], removed: [], reason: e.message };
  }
  if (!manifest) return { status: 'modified', changed: [], added: [], removed: [], reason: 'no .ai/manifest.json' };
  const recorded = manifest.tools !== null && typeof manifest.tools === 'object' ? manifest.tools : {};
  const diff = diffHashes(actual, recorded);
  const status = diff.changed.length || diff.added.length || diff.removed.length ? 'modified' : 'self-check-ok';
  return { status, ...diff };
}

/** The .ai dir when the module at `url` runs from a vendored <.ai>/tools/scripts directory, else null. */
export function vendoredAiDir(url) {
  let dir;
  try {
    dir = fs.realpathSync(path.dirname(fileURLToPath(url)));
  } catch {
    return null;
  }
  if (!dir.endsWith(`${path.sep}.ai${path.sep}tools${path.sep}scripts`)) return null;
  const aiDir = path.dirname(path.dirname(dir));
  return fs.existsSync(path.join(aiDir, 'manifest.json')) ? aiDir : null;
}

/** For entry scripts: true when running from a vendored copy whose tools fail the self-check (and trust was not given). */
export function vendoredToolsRefused(url, argv) {
  if (argv.includes(TRUST_FLAG)) return false;
  const aiDir = vendoredAiDir(url);
  return aiDir !== null && selfCheckTools(aiDir).status !== 'self-check-ok';
}
